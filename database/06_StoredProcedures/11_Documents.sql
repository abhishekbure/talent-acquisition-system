/* ============================================================================
   TAMS - 06_StoredProcedures / 11_Documents.sql   (Phase 8)
   Document METADATA and access rules. The files themselves live on local disk outside any served folder,
   under a generated GUID name (never the user's file name); the API writes/reads them, the database decides
   who may see, add or remove each document.
   Owners: Candidate (resume, certificates, ...), Contractor (optionally tied to a compliance record),
           Employee (HR documents), Contract (signed contract, customer-scoped).
   ========================================================================== */
USE TalentAcquisitionDB;
GO

/* May @ActorUserId add / remove documents of this owner? (existence of the owner is checked by the callers) */
CREATE OR ALTER FUNCTION doc.fn_CanManageOwner (@ActorUserId INT, @OwnerType VARCHAR(12), @OwnerId INT)
RETURNS BIT
AS
BEGIN
    IF sec.fn_UserHasRole(@ActorUserId, N'Administrator') = 1 RETURN 1;
    IF @OwnerType = 'Candidate'
        RETURN CASE WHEN sec.fn_UserHasRole(@ActorUserId, N'Recruiter') = 1 OR sec.fn_UserHasRole(@ActorUserId, N'HRManager') = 1
                      OR cand.fn_CandidateIdForUser(@ActorUserId) = @OwnerId THEN 1 ELSE 0 END;
    IF @OwnerType = 'Contractor'
        RETURN CASE WHEN sec.fn_UserHasRole(@ActorUserId, N'Recruiter') = 1 OR staff.fn_ContractorIdForUser(@ActorUserId) = @OwnerId THEN 1 ELSE 0 END;
    IF @OwnerType = 'Employee'
        RETURN sec.fn_UserHasRole(@ActorUserId, N'HRManager');
    IF @OwnerType = 'Contract'
        RETURN sec.fn_UserHasRole(@ActorUserId, N'Recruiter');
    RETURN 0;
END
GO

/* May @ActorUserId read this document? Deleted documents are never readable. */
CREATE OR ALTER FUNCTION doc.fn_CanAccessDocument (@ActorUserId INT, @DocumentId INT)
RETURNS BIT
AS
BEGIN
    DECLARE @ot VARCHAR(12), @oid INT, @cust INT, @del BIT;
    SELECT @ot = OwnerType, @oid = OwnerId, @cust = CustomerId, @del = IsDeleted FROM doc.Documents WHERE DocumentId = @DocumentId;
    IF @ot IS NULL OR @del = 1 RETURN 0;
    IF sec.fn_UserHasRole(@ActorUserId, N'Administrator') = 1 RETURN 1;
    DECLARE @rec BIT = sec.fn_UserHasRole(@ActorUserId, N'Recruiter'), @hr BIT = sec.fn_UserHasRole(@ActorUserId, N'HRManager');
    DECLARE @myCand INT = cand.fn_CandidateIdForUser(@ActorUserId), @myCust INT = sec.fn_UserCustomerId(@ActorUserId), @myCtr INT = staff.fn_ContractorIdForUser(@ActorUserId);

    IF @ot = 'Candidate'
    BEGIN
        IF @rec = 1 OR @hr = 1 OR @myCand = @oid RETURN 1;
        -- a customer may read a candidate's RESUME (only) once it has shortlisted that candidate for one of its own requests
        IF @myCust IS NOT NULL
           AND EXISTS (SELECT 1 FROM cand.CandidateDocuments cd WHERE cd.DocumentId = @DocumentId AND cd.DocType = 'Resume')
           AND EXISTS (SELECT 1 FROM staff.SubmittedCandidates s WHERE s.CandidateId = @oid AND s.CustomerId = @myCust AND s.Status IN ('Shortlisted', 'Interview', 'Selected'))
            RETURN 1;
        RETURN 0;
    END
    IF @ot = 'Contractor' RETURN CASE WHEN @rec = 1 OR @myCtr = @oid THEN 1 ELSE 0 END;
    IF @ot = 'Employee'
        RETURN CASE WHEN @hr = 1 OR EXISTS (SELECT 1 FROM hr.Employees e WHERE e.EmployeeId = @oid AND e.CandidateId = @myCand) THEN 1 ELSE 0 END;
    IF @ot = 'Contract'
        RETURN CASE WHEN @rec = 1 OR (@cust IS NOT NULL AND @cust = @myCust)
                      OR EXISTS (SELECT 1 FROM staff.Contracts ct JOIN staff.Placements p ON p.PlacementId = ct.PlacementId WHERE ct.ContractId = @oid AND p.ContractorId = @myCtr)
                    THEN 1 ELSE 0 END;
    RETURN 0;
END
GO

CREATE OR ALTER PROCEDURE doc.usp_AddDocument
    @ActorUserId INT, @OwnerType VARCHAR(12), @OwnerId INT, @DocType VARCHAR(20) = NULL,
    @StoredFileName NVARCHAR(100), @OriginalFileName NVARCHAR(260), @ContentType NVARCHAR(100), @SizeBytes BIGINT, @Sha256 BINARY(32),
    @ComplianceId INT = NULL, @IsPrimaryResume BIT = 0
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT OFF;
    DECLARE @own BIT = CASE WHEN @@TRANCOUNT = 0 THEN 1 ELSE 0 END;
    BEGIN TRY
        IF @own = 1 BEGIN BEGIN TRANSACTION; END ELSE BEGIN SAVE TRANSACTION sp_AddDoc; END
        EXEC sec.usp_Authorize @ActorUserId, N'Candidate,Contractor,Recruiter,HRManager,Administrator';
        IF @OwnerType NOT IN ('Candidate', 'Contractor', 'Employee', 'Contract') THROW 50001, N'Owner type must be Candidate, Contractor, Employee or Contract.', 1;
        -- the stored name is generated by the API: a GUID plus extension, never a path
        IF @StoredFileName IS NULL OR LEN(@StoredFileName) < 33 OR @StoredFileName LIKE N'%[\/:]%' OR @StoredFileName LIKE N'%..%' THROW 50001, N'Invalid stored file name.', 1;
        IF LEN(LTRIM(RTRIM(ISNULL(@OriginalFileName, N'')))) = 0 THROW 50001, N'The original file name is required.', 1;
        IF ISNULL(@SizeBytes, 0) < 1 OR @SizeBytes > 10485760 THROW 50001, N'Documents must be between 1 byte and 10 MB.', 1;
        IF @Sha256 IS NULL OR DATALENGTH(@Sha256) <> 32 THROW 50001, N'A SHA-256 hash is required.', 1;

        DECLARE @cust INT = NULL;
        IF @OwnerType = 'Candidate' AND NOT EXISTS (SELECT 1 FROM cand.Candidates WHERE CandidateId = @OwnerId) THROW 50004, N'Candidate not found.', 1;
        IF @OwnerType = 'Contractor' AND NOT EXISTS (SELECT 1 FROM staff.Contractors WHERE ContractorId = @OwnerId) THROW 50004, N'Contractor not found.', 1;
        IF @OwnerType = 'Employee' AND NOT EXISTS (SELECT 1 FROM hr.Employees WHERE EmployeeId = @OwnerId) THROW 50004, N'Employee not found.', 1;
        IF @OwnerType = 'Contract'
        BEGIN
            SELECT @cust = CustomerId FROM staff.Contracts WHERE ContractId = @OwnerId;
            IF @cust IS NULL THROW 50004, N'Contract not found.', 1;
        END
        IF doc.fn_CanManageOwner(@ActorUserId, @OwnerType, @OwnerId) = 0 THROW 50004, N'Owner not found.', 1;   -- someone else's records look missing

        IF @OwnerType = 'Candidate'
        BEGIN
            SET @DocType = ISNULL(@DocType, 'Resume');
            IF @DocType NOT IN ('Resume', 'CoverLetter', 'Certificate', 'Identity', 'Other') THROW 50001, N'Document type must be Resume, CoverLetter, Certificate, Identity or Other.', 1;
        END
        IF @OwnerType = 'Employee'
        BEGIN
            SET @DocType = ISNULL(@DocType, 'Other');
            IF @DocType NOT IN ('Contract', 'Identity', 'Offer', 'Payroll', 'Certificate', 'Other') THROW 50001, N'Document type must be Contract, Identity, Offer, Payroll, Certificate or Other.', 1;
        END
        IF @ComplianceId IS NOT NULL AND (@OwnerType <> 'Contractor' OR NOT EXISTS (SELECT 1 FROM staff.ComplianceRecords WHERE ComplianceId = @ComplianceId AND ContractorId = @OwnerId))
            THROW 50004, N'Compliance record not found.', 1;

        INSERT doc.Documents (OwnerType, OwnerId, CustomerId, StoredFileName, OriginalFileName, ContentType, SizeBytes, Sha256, UploadedByUserId)
        VALUES (@OwnerType, @OwnerId, @cust, @StoredFileName, LTRIM(RTRIM(@OriginalFileName)), @ContentType, @SizeBytes, @Sha256, @ActorUserId);
        DECLARE @id INT = SCOPE_IDENTITY();

        IF @OwnerType = 'Candidate'
        BEGIN
            -- the first resume becomes the primary one; asking for primary moves the flag
            IF @DocType = 'Resume' AND (@IsPrimaryResume = 1 OR NOT EXISTS (SELECT 1 FROM cand.CandidateDocuments cd JOIN doc.Documents d ON d.DocumentId = cd.DocumentId
                                                                          WHERE cd.CandidateId = @OwnerId AND cd.IsPrimaryResume = 1 AND d.IsDeleted = 0))
            BEGIN
                UPDATE cand.CandidateDocuments SET IsPrimaryResume = 0 WHERE CandidateId = @OwnerId AND IsPrimaryResume = 1;
                SET @IsPrimaryResume = 1;
            END
            ELSE SET @IsPrimaryResume = 0;
            INSERT cand.CandidateDocuments (CandidateId, DocumentId, DocType, IsPrimaryResume) VALUES (@OwnerId, @id, @DocType, @IsPrimaryResume);
        END
        ELSE IF @OwnerType = 'Employee'
            INSERT hr.EmployeeDocuments (EmployeeId, DocumentId, DocType) VALUES (@OwnerId, @id, @DocType);
        ELSE IF @OwnerType = 'Contract'
            UPDATE staff.Contracts SET DocumentId = @id WHERE ContractId = @OwnerId;
        ELSE IF @ComplianceId IS NOT NULL
            -- a new proof from the contractor must be verified again; staff uploads keep the current verification
            UPDATE staff.ComplianceRecords
               SET DocumentId = @id,
                   Status = CASE WHEN staff.fn_ContractorIdForUser(@ActorUserId) = @OwnerId AND sec.fn_IsStaff(@ActorUserId) = 0 THEN 'Pending' ELSE Status END,
                   VerifiedByUserId = CASE WHEN staff.fn_ContractorIdForUser(@ActorUserId) = @OwnerId AND sec.fn_IsStaff(@ActorUserId) = 0 THEN NULL ELSE VerifiedByUserId END,
                   VerifiedAt = CASE WHEN staff.fn_ContractorIdForUser(@ActorUserId) = @OwnerId AND sec.fn_IsStaff(@ActorUserId) = 0 THEN NULL ELSE VerifiedAt END
             WHERE ComplianceId = @ComplianceId;

        IF @own = 1 COMMIT;
        SELECT @id AS DocumentId, @OwnerType AS OwnerType, @OwnerId AS OwnerId, @DocType AS DocType, @IsPrimaryResume AS IsPrimaryResume;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() = -1 ROLLBACK TRANSACTION; ELSE IF @own = 1 AND @@TRANCOUNT > 0 ROLLBACK TRANSACTION; ELSE IF @own = 0 AND XACT_STATE() = 1 ROLLBACK TRANSACTION sp_AddDoc;
        THROW;
    END CATCH
END
GO

/* Documents of one owner that the caller may see (a customer sees only resumes of candidates it has shortlisted). */
CREATE OR ALTER PROCEDURE doc.usp_ListDocuments @ActorUserId INT, @OwnerType VARCHAR(12), @OwnerId INT
AS
BEGIN
    SET NOCOUNT ON;
    EXEC sec.usp_Authorize @ActorUserId, N'Candidate,Contractor,Customer,Recruiter,HRManager,Administrator';
    IF @OwnerType NOT IN ('Candidate', 'Contractor', 'Employee', 'Contract') THROW 50001, N'Owner type must be Candidate, Contractor, Employee or Contract.', 1;
    DECLARE @canManage BIT = doc.fn_CanManageOwner(@ActorUserId, @OwnerType, @OwnerId);
    SELECT d.DocumentId, d.OwnerType, d.OwnerId, COALESCE(cd.DocType, ed.DocType, CASE WHEN cr.ComplianceId IS NOT NULL THEN 'Compliance' WHEN d.OwnerType = 'Contract' THEN 'Contract' ELSE 'Other' END) AS DocType,
           ISNULL(cd.IsPrimaryResume, 0) AS IsPrimaryResume, cr.ComplianceId, cr.RecordType AS ComplianceType,
           d.OriginalFileName, d.ContentType, d.SizeBytes, d.UploadedAt, u.DisplayName AS UploadedBy, @canManage AS CanDelete
    FROM doc.Documents d
    LEFT JOIN cand.CandidateDocuments cd ON cd.DocumentId = d.DocumentId
    LEFT JOIN hr.EmployeeDocuments ed ON ed.DocumentId = d.DocumentId
    LEFT JOIN staff.ComplianceRecords cr ON cr.DocumentId = d.DocumentId
    JOIN sec.Users u ON u.UserId = d.UploadedByUserId
    WHERE d.OwnerType = @OwnerType AND d.OwnerId = @OwnerId AND d.IsDeleted = 0
      AND doc.fn_CanAccessDocument(@ActorUserId, d.DocumentId) = 1
    ORDER BY d.UploadedAt DESC, d.DocumentId DESC;
END
GO

/* Everything the API needs to stream the file - only after the access check. 50004 hides documents the caller may not see. */
CREATE OR ALTER PROCEDURE doc.usp_GetDocumentForDownload @ActorUserId INT, @DocumentId INT
AS
BEGIN
    SET NOCOUNT ON;
    EXEC sec.usp_Authorize @ActorUserId, N'Candidate,Contractor,Customer,Recruiter,HRManager,Administrator';
    IF doc.fn_CanAccessDocument(@ActorUserId, @DocumentId) = 0 THROW 50004, N'Document not found.', 1;
    SELECT DocumentId, StoredFileName, OriginalFileName, ContentType, SizeBytes, Sha256, UploadedAt FROM doc.Documents WHERE DocumentId = @DocumentId;
END
GO

/* Soft delete: the record (and file) are kept for the retention period; links from contracts / compliance records are cleared. */
CREATE OR ALTER PROCEDURE doc.usp_DeleteDocument @ActorUserId INT, @DocumentId INT
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT OFF;
    DECLARE @own BIT = CASE WHEN @@TRANCOUNT = 0 THEN 1 ELSE 0 END;
    BEGIN TRY
        IF @own = 1 BEGIN BEGIN TRANSACTION; END ELSE BEGIN SAVE TRANSACTION sp_DelDoc; END
        EXEC sec.usp_Authorize @ActorUserId, N'Candidate,Contractor,Recruiter,HRManager,Administrator';
        DECLARE @ot VARCHAR(12), @oid INT;
        SELECT @ot = OwnerType, @oid = OwnerId FROM doc.Documents WITH (UPDLOCK) WHERE DocumentId = @DocumentId AND IsDeleted = 0;
        IF @ot IS NULL OR doc.fn_CanManageOwner(@ActorUserId, @ot, @oid) = 0 OR doc.fn_CanAccessDocument(@ActorUserId, @DocumentId) = 0 THROW 50004, N'Document not found.', 1;
        UPDATE doc.Documents SET IsDeleted = 1, DeletedAt = SYSUTCDATETIME() WHERE DocumentId = @DocumentId;   -- DeletedAt: the file is purged after the retention period (Phase 12)
        UPDATE staff.Contracts SET DocumentId = NULL WHERE DocumentId = @DocumentId;
        UPDATE staff.ComplianceRecords SET DocumentId = NULL WHERE DocumentId = @DocumentId;
        UPDATE cand.CandidateDocuments SET IsPrimaryResume = 0 WHERE DocumentId = @DocumentId;
        IF @own = 1 COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() = -1 ROLLBACK TRANSACTION; ELSE IF @own = 1 AND @@TRANCOUNT > 0 ROLLBACK TRANSACTION; ELSE IF @own = 0 AND XACT_STATE() = 1 ROLLBACK TRANSACTION sp_DelDoc;
        THROW;
    END CATCH
END
GO

/* Recruiter verifies or rejects a contractor's compliance record (a document must be attached to verify). */
CREATE OR ALTER PROCEDURE staff.usp_DecideCompliance @ActorUserId INT, @ComplianceId INT, @Status VARCHAR(10), @Notes NVARCHAR(500) = NULL
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT OFF;
    DECLARE @own BIT = CASE WHEN @@TRANCOUNT = 0 THEN 1 ELSE 0 END;
    BEGIN TRY
        IF @own = 1 BEGIN BEGIN TRANSACTION; END ELSE BEGIN SAVE TRANSACTION sp_DecideComp; END
        EXEC sec.usp_Authorize @ActorUserId, N'Recruiter,Administrator';
        IF @Status NOT IN ('Verified', 'Rejected') THROW 50001, N'Status must be Verified or Rejected.', 1;
        IF @Status = 'Rejected' AND LEN(LTRIM(RTRIM(ISNULL(@Notes, N'')))) = 0 THROW 50001, N'A reason is required when rejecting.', 1;
        DECLARE @doc INT, @found BIT = 0, @ctrUser INT, @type VARCHAR(20);
        SELECT @found = 1, @doc = cr.DocumentId, @ctrUser = k.UserId, @type = cr.RecordType
        FROM staff.ComplianceRecords cr WITH (UPDLOCK) JOIN staff.Contractors k ON k.ContractorId = cr.ContractorId WHERE cr.ComplianceId = @ComplianceId;
        IF @found = 0 THROW 50004, N'Compliance record not found.', 1;
        IF @Status = 'Verified' AND @doc IS NULL THROW 50002, N'Attach the supporting document before verifying.', 1;
        UPDATE staff.ComplianceRecords SET Status = @Status, VerifiedByUserId = @ActorUserId, VerifiedAt = SYSUTCDATETIME(), Notes = ISNULL(@Notes, Notes) WHERE ComplianceId = @ComplianceId;
        IF @ctrUser IS NOT NULL
        BEGIN
            DECLARE @subj NVARCHAR(300) = N'Your ' + @type + N' compliance record was ' + LOWER(@Status);
            DECLARE @key NVARCHAR(180) = N'COMPL:' + CAST(@ComplianceId AS NVARCHAR(12)) + N':' + @Status + N':' + CONVERT(NVARCHAR(19), SYSUTCDATETIME(), 126);
            EXEC notify.usp_Enqueue 'COMPLIANCE_DECISION', @ctrUser, @subj, @Notes, @key, 'Compliance', @ComplianceId;
        END
        IF @own = 1 COMMIT;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() = -1 ROLLBACK TRANSACTION; ELSE IF @own = 1 AND @@TRANCOUNT > 0 ROLLBACK TRANSACTION; ELSE IF @own = 0 AND XACT_STATE() = 1 ROLLBACK TRANSACTION sp_DecideComp;
        THROW;
    END CATCH
END
GO

/* audit trail for document metadata (upload = I, soft delete = U) with the acting user */
CREATE OR ALTER TRIGGER doc.trg_Documents_Audit ON doc.Documents AFTER INSERT, UPDATE, DELETE AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM inserted) AND NOT EXISTS (SELECT 1 FROM deleted) RETURN;
    DECLARE @actor INT = NULLIF(CAST(SUBSTRING(CONTEXT_INFO(), 1, 4) AS INT), 0);
    INSERT audit.AuditLogs (TableName, RecordId, Action, OldValues, NewValues, ChangedByUserId)
    SELECT N'doc.Documents', CAST(COALESCE(i.DocumentId, d.DocumentId) AS NVARCHAR(50)),
           CASE WHEN i.DocumentId IS NOT NULL AND d.DocumentId IS NOT NULL THEN 'U' WHEN i.DocumentId IS NOT NULL THEN 'I' ELSE 'D' END,
           CASE WHEN d.DocumentId IS NOT NULL THEN CAST((SELECT x.DocumentId, x.OwnerType, x.OwnerId, x.OriginalFileName, x.SizeBytes, x.IsDeleted FROM deleted x WHERE x.DocumentId = d.DocumentId FOR XML RAW('row'), ELEMENTS) AS NVARCHAR(MAX)) END,
           CASE WHEN i.DocumentId IS NOT NULL THEN CAST((SELECT x.DocumentId, x.OwnerType, x.OwnerId, x.OriginalFileName, x.SizeBytes, x.IsDeleted FROM inserted x WHERE x.DocumentId = i.DocumentId FOR XML RAW('row'), ELEMENTS) AS NVARCHAR(MAX)) END,
           @actor
    FROM inserted i FULL OUTER JOIN deleted d ON d.DocumentId = i.DocumentId;
END
GO

/* Compliance decisions (Verify/Reject) and proof uploads change these rows; record who did it. */
CREATE OR ALTER TRIGGER staff.trg_ComplianceRecords_Audit ON staff.ComplianceRecords AFTER INSERT, UPDATE, DELETE AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM inserted) AND NOT EXISTS (SELECT 1 FROM deleted) RETURN;
    DECLARE @actor INT = NULLIF(CAST(SUBSTRING(CONTEXT_INFO(), 1, 4) AS INT), 0);
    INSERT audit.AuditLogs (TableName, RecordId, Action, OldValues, NewValues, ChangedByUserId)
    SELECT N'staff.ComplianceRecords', CAST(COALESCE(i.ComplianceId, d.ComplianceId) AS NVARCHAR(50)),
           CASE WHEN i.ComplianceId IS NOT NULL AND d.ComplianceId IS NOT NULL THEN 'U' WHEN i.ComplianceId IS NOT NULL THEN 'I' ELSE 'D' END,
           CASE WHEN d.ComplianceId IS NOT NULL THEN CAST((SELECT x.ComplianceId, x.ContractorId, x.RecordType, x.Status, x.ExpiresOn, x.DocumentId, x.VerifiedByUserId, x.Notes FROM deleted x WHERE x.ComplianceId = d.ComplianceId FOR XML RAW('row'), ELEMENTS) AS NVARCHAR(MAX)) END,
           CASE WHEN i.ComplianceId IS NOT NULL THEN CAST((SELECT x.ComplianceId, x.ContractorId, x.RecordType, x.Status, x.ExpiresOn, x.DocumentId, x.VerifiedByUserId, x.Notes FROM inserted x WHERE x.ComplianceId = i.ComplianceId FOR XML RAW('row'), ELEMENTS) AS NVARCHAR(MAX)) END,
           @actor
    FROM inserted i FULL OUTER JOIN deleted d ON d.ComplianceId = i.ComplianceId;
END
GO
